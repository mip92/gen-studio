TARGET = os.path.join(os.path.dirname(os.path.abspath(__file__)), "seed_minibus_shots.py")


def main():
    apply = "--apply" in sys.argv
    src = io.open(TARGET, encoding="utf-8").read().split("\n")
    changed = 0
    for i, line in enumerate(src):
        m = re.match(r'^\("([A-Z0-9_]+)",', line)
        if not m or m.group(1) not in VO:
            continue
        j = i + 1
        if not re.match(r'^ ".*",$', src[j]):
            print(f"  ! {m.group(1)}: строка озвучки не на своём месте")
            continue
        new = VO[m.group(1)].replace('"', '\\"')
        if src[j][2:-2] != new:
            src[j] = f' "{new}",'
            changed += 1
    print(f"строк в проходе: {len(VO)}   к замене: {changed}")
    if apply and changed:
        io.open(TARGET, "w", encoding="utf-8", newline="\n").write("\n".join(src))
        print("применено")


if __name__ == "__main__":
    main()

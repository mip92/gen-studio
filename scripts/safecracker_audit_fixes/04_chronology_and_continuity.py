import json, sys, urllib.request

API = "http://localhost:4000"
PROJ = "3884f4d5-4090-4c93-9518-25dbff658673"

VO = {
"A3_SH04": "у тебя одно правило, и ты не нарушишь его ни разу: сначала слушать, и только потом трогать.",
"A4_SH13": "и говоришь ему одно слово: минута.",
"A5_SH02": "минуту ты назвал заранее, а вышло тридцать четыре секунды, и он это тоже засёк.",
"A5_SH03": "ты не заходишь внутрь ни на шаг, и такое правило держишь потом все четыре года.",
"A6_SH07": "жена говорит, чтобы ты немедленно это прекратил, и за восемь лет это единственный раз, когда она повышает голос.",
"A6_SH10": "двести дверей за два года, и ни из одной ты не вынес ни одной вещи.",
"A7_SH09": "ты смотришь на неё дольше, чем смотрел на любую дверь за эти четыре года.",
"A7_SH13": "ты кладёшь щуп в нагрудный карман так же, как клал его пятнадцать лет подряд.",
"A8_SH07": "и первый раз за четыре года тебе хочется посмотреть, что там внутри.",
"A9_SH07": "сын вырастает, и в тридцать шесть он стоит у чужой двери, как когда-то стоял ты.",
"F_SH06":  "ты встаёшь, снимаешь халат и берёшь с полки свёрток, который не разворачивал двадцать семь лет.",
}

# §3: щуп лежит на верстаке (F_SH08) — из прихожей его надо убрать
POS = [("F_SH11",
        ", the copper probe lying beside them",
        "")]


def req(method, path, body=None):
    data = json.dumps(body, ensure_ascii=False).encode("utf-8") if body is not None else None
    r = urllib.request.Request(API + path, data=data, method=method,
                               headers={"Content-Type": "application/json; charset=utf-8"})
    with urllib.request.urlopen(r, timeout=60) as resp:
        raw = resp.read().decode("utf-8")
        return json.loads(raw) if raw.strip() else {}


def main():
    res = req("GET", "/projects/%s/shots?take=400" % PROJ)
    items = res["items"] if isinstance(res, dict) and "items" in res else res
    by_code = {s["shotCode"]: s for s in items}

    for code, text in VO.items():
        assert not text[0].isupper() and text.endswith(".") and text.count(".") == 1, code
        assert len(text.split()) >= 6, "%s: %d слов" % (code, len(text.split()))
        req("PATCH", "/tts/shots/%s/narration" % by_code[code]["id"], {"text": text})
    print("озвучка: %d строк" % len(VO))

    for code, old, new in POS:
        sh = by_code[code]
        pf = dict(sh["promptFields"])
        assert old in pf["positive"], code
        pf["positive"] = pf["positive"].replace(old, new, 1)
        req("PATCH", "/shots/%s" % sh["id"], {"promptFields": pf})
        print("кадр", code, "— щуп убран из прихожей")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()

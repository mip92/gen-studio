def req(method, path, body=None):
    data = json.dumps(body, ensure_ascii=False).encode("utf-8") if body is not None else None
    r = urllib.request.Request(API + path, data=data, method=method,
                               headers={"Content-Type": "application/json; charset=utf-8"})
    with urllib.request.urlopen(r, timeout=60) as resp:
        return json.loads(resp.read().decode("utf-8"))


def main():
    shots = req("GET", "/projects/%s/shots?take=400" % PROJ)
    items = shots["items"] if isinstance(shots, dict) and "items" in shots else shots
    by_code = {s["shotCode"]: s["id"] for s in items}

    ok, bad = 0, []
    for code, text in NEW.items():
        if code not in by_code:
            bad.append((code, "нет такого кадра")); continue
        # f5: одно предложение, строчная первая буква, единственная точка в конце
        assert not text[0].isupper(), code
        assert text.endswith("."), code
        assert text.count(".") == 1, code
        assert len(text.split()) >= 6, "%s: %d слов" % (code, len(text.split()))
        try:
            req("PATCH", "/tts/shots/%s/narration" % by_code[code], {"text": text})
            ok += 1
        except Exception as exc:  # noqa: BLE001
            bad.append((code, str(exc)[:120]))
    print("озвучка обновлена: %d из %d" % (ok, len(NEW)))
    for c, e in bad:
        print("  ОШИБКА %s: %s" % (c, e))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()

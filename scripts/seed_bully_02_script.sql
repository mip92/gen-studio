## АКТ 1 — Сверло (14 кадров)

Первый кадр: рука в станке. Не подход к станку, не мастерская общим планом — рука,
намотанный рукав, визг сверлильного станка.

Тебе четырнадцать. Ты в школьной мастерской, вторая смена, восемь верстаков,
запах горячей стружки и мастики. У Юры Соколова рукав халата затянуло в патрон
сверлильного станка, и его тащит к столу за левую руку.

Ты успеваешь раньше трудовика. Ты бьёшь ладонью по грибку, вырубаешь станок,
разжимаешь патрон и вытаскиваешь рукав. Двадцать секунд. У Юры на предплечье
багровая полоса и порванный рукав, и он не кричит — он молчит и смотрит в пол.

Кузьмич, трудовик, кладёт тебе руку на плечо при всём классе: «Руки у тебя,
Славка, взрослые». Одиннадцать пацанов это слышат.

**Крючок (кадры 6–8):** «Сейчас я расскажу, как эти руки на тридцать лет стали
единственным, что у тебя есть, и почему ты до сих пор не можешь ими ничего
починить у себя дома».

Кризис НЕ закрывается: Юра уходит с урока, прижимая рукав, и на перемене трое
уже повторяют, как он молчал. Ты не останавливаешь. Это первый выбор.

## АКТ 2 — Оргстекло (14 кадров)

Через неделю. Юра приносит в мастерскую отлитый им брелок (и убирает его потом в портфель — оттуда его и достанет Толик в акте 4): кусок оргстекла
40 на 25 миллиметров, внутри залит засушенный василёк. Он сделал его для матери,
на восьмое марта, за четыре вечера.

Кузьмич показывает брелок всему классу и говорит, что так он сам не умеет.
Ты стоишь у своего верстака с недоделанной табуреткой, и впервые тебя хвалят
не первым.

Толик Мишин, рыжий, с бляхой, натёртой до зеркала, произносит вслух то, что ты
подумал: «Соколов, ты чё, девочка? Цветочки заливаешь». Класс смеётся. Ты не
смеёшься — ты киваешь. Кивок стоит дешевле смеха и весит больше.

Так ты узнаёшь механизм: тебе не нужно ничего делать самому. Достаточно
одобрить. Одиннадцать пацанов ждут твоего лица.

## АКТ 3 — Прозвище (14 кадров)

Октябрь. Ты даёшь Юре прозвище — «Гербарий». Одно слово, на перемене, вслух.
К пятнице его зовут так шесть человек, к среде — весь класс, к концу месяца —
параллель.

Ты замечаешь арифметику: имя стирается за девятнадцать дней. Человека зовут
Юрой только дома и на перекличке.

Ритка Белова, чёрные волосы в две косы, красная заколка-краб, говорит тебе у
окна на втором этаже: «Тебе не стыдно?» Ты отвечаешь: «Я его не трогал».
И это правда, и это первая ложь, которую ты рассказываешь себе.

## АКТ 4 — Портфель (14 кадров)

Ноябрь. Портфель Юры находят на батарее у окна второго этажа — учебники
разбухли, обложки покоробило. Никто не видел кто.

Ты видел кто. Толик. Ты стоял в трёх метрах и смотрел в окно.

Классная, Нина Петровна, часики циферблатом внутрь запястья, ставит класс и
спрашивает весь урок. Никто не говорит. Ты тоже не говоришь — и в этот момент
понимаешь, что молчат не потому, что боятся Толика. Молчат, потому что смотрят
на тебя.

Впервые ты пробуешь власть на вес. Она лёгкая.

**Лейтмотив:** после урока Толик показывает тебе брелок Юры — вытащил из
портфеля. Ты берёшь его в руку. Оргстекло тёплое. Ты кладёшь его в карман.

## АКТ 5 — Котельная (14 кадров)

Декабрь, минус восемнадцать. Задворки за школьной котельной, куда не выходят
окна. Четверо. Ты пятый.

Юру ставят к кирпичной стене и заставляют говорить своё прозвище вслух.
Он говорит. Двенадцать раз, пока Толику не надоест.

Ты стоишь и считаешь до двенадцати. Ты не бьёшь, ты не держишь, ты не говоришь
ни слова. Ты просто там, и пока ты там — это можно.

Домой ты идёшь один, и в кармане у тебя оргстекло.

## АКТ 6 — Возврат (14 кадров)

Февраль. Ты приходишь в школу на сорок минут раньше и кладёшь брелок Юре в
парту. Никто не видит. Ты не говоришь ему ничего.

Он находит на первом уроке. Он оборачивается и ищет глазами — и находит тебя.
И ты отводишь взгляд первым.

Три дня всё почти нормально. Он опять сидит прямо.

На четвёртый Толик спрашивает при всех: «Слав, а ты чё, за Гербария теперь?»
Одиннадцать лиц поворачиваются к тебе.

Ты говоришь: «Да плевать мне на него».

## АКТ 7 — Оргстекло ломается (16 кадров)

Тот же день, большая перемена, коридор второго этажа. Толик выхватывает брелок и
щёлкает им о батарею. Оргстекло лопается по диагонали, василёк выпадает.

Юра стоит на коленях и собирает с пола сухие лепестки. Двадцать шесть человек
смотрят. Ты стоишь ближе всех.

Ты мог сказать одно слово. У тебя оно было. Ты промолчал, потому что накануне
уже сказал «плевать», и взять назад было бы дороже.

Юра переводится в другую школу восемнадцатого марта. Больше ты его не видишь.

## АКТ 8 — Тридцать лет (18 кадров)

Тебе сорок четыре. Ты слесарь в гаражном кооперативе, руки те же, работа
честная. Жена ушла шесть лет назад, сын звонит на день рождения.

Ты умеешь всё, кроме одного: у тебя дома третий год не закрывается балконная
дверь, и ты к ней не подходишь.

Одноклассники зовут на встречу класса — тридцать лет с той мастерской. Ты идёшь. Толик приезжает
на машине, громкий, с фотографиями внуков. Ритка Белова — учительница младших
классов, косы те же, заколки нет.

Ты спрашиваешь про Юру. Ритка говорит: «Он умер в тридцать один. Сердце».
И добавляет спокойно, без обвинения: «Он приезжал сюда один раз, в двухтысячном.
Стоял у школы минут двадцать и уехал».

## ФИНАЛ — Ящик (22 кадра)

Ты возвращаешься домой в час ночи и открываешь нижний ящик верстака, куда
тридцать лет складываешь то, что нельзя выбросить.

Брелок там. Ты вынес его из школы в тот же день, когда он лопнул, — подобрал с
пола, когда все ушли, и никому не сказал.

Ты садишься за верстак и склеиваешь его. У тебя получается: руки взрослые.
Шов виден, василька внутри нет — он рассыпался тридцать лет назад.

**Кода, четвёртая стена (БЕЗ морали — правило Track B «no-moral coda»):**
«Ты думаешь, что ты ничего не делал. Ты и правда ничего не делал. Одиннадцать
человек тогда ждали твоего лица, каждый раз только его, и каждый раз ты давал
им то, которое обходилось тебе дешевле всего». Никакого указания зрителю не
следует: последнее слово — факт о герое, а не урок.

**Балконная дверь НЕ чинится.** Он склеивает предмет, мёртвый тридцать лет, и
по-прежнему не подходит к двери, с которой живёт. Починка была бы искуплением,
которого он не заработал.

**Финальный кадр:** склеенный брелок на верстаке под лампой, шов поперёк, внутри
пусто.

**Дисклеймер:** «Эта история вымышлена. Все совпадения с реальными людьми и
событиями случайны. Не повторяй чужих ошибок».


TARGET = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                      "seed_towtruck_shots.py")


def main():
    apply = "--apply" in sys.argv
    src = io.open(TARGET, encoding="utf-8").read().split("\n")
    hits, missing, changed = set(), [], 0
    for i, line in enumerate(src):
        m = re.match(r'^\("([A-Z0-9_]+)",', line)
        if not m:
            continue
        code = m.group(1)
        hits.add(code)
        if code not in VO:
            missing.append(code)
            continue
        j = i + 1
        if not re.match(r'^ ".*",$', src[j]):
            print(f"  ! {code}: строка озвучки не на своём месте, пропуск")
            continue
        old = src[j][2:-2]
        new = VO[code].replace('"', '\\"')
        if old == new:
            continue
        changed += 1
        src[j] = f' "{new}",'
    for code in sorted(set(VO) - hits):
        print(f"  ! {code}: кода нет в сидере")
    for code in missing:
        print(f"  ! {code}: нет новой озвучки")
    print(f"кадров в сидере: {len(hits)}   новых строк: {len(VO)}   к замене: {changed}")
    words = sum(len(v.split()) for v in VO.values())
    print(f"слов после правки: {words}   ≈ {words / 140 + len(VO) * 0.5 / 60:.1f} мин")
    if apply and changed:
        io.open(TARGET, "w", encoding="utf-8", newline="\n").write("\n".join(src))
        print("применено")
    elif not apply:
        print("сухой прогон, для записи --apply")


if __name__ == "__main__":
    main()

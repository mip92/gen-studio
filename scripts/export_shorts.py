"""
Build YouTube-Shorts CapCut drafts for a gen-studio project.

A "short" is a curated 20-45 s vertical (9:16) cut assembled from a HANDFUL of
the project's most intriguing already-rendered shots — the teaser reels that
drive viewers to the full film. This is the sibling of export_capcut.py: same
draft machinery, but per-short, vertical, and only over a hand-picked subset of
shots. One CapCut draft per short (so each opens as its own project, "по одной
штуке").

  Full film  ->  ExportsService.buildManifest  ->  export_capcut.py  (16:9, all shots)
  Shorts     ->  this script                    ->  export_capcut.py  (9:16, subset)

Selection is provided by a PLAN json (for now hand-authored by the operator;
in future generated by a local LLM that scores "интересность"):

  {
    "project": "painter",              # slug or id
    "fill": "cover",                   # optional, default "cover" — enlarge each
                                       #   clip to FILL the 9:16 frame (crop sides).
                                       #   "fit" + background_fill:"blur" = letterbox.
    "background_fill": "",             # optional, used only when fill != "cover"
    "width": 1080, "height": 1920,     # optional, default vertical 1080x1920
    "fps": 30,                         # optional, default 30
    "shorts": [
      { "slug": "hook",  "title": "Серый приговор", "shots": ["CO_SH01", ...] },
      { "slug": "revolt","title": "Тайный бунт",    "shots": ["A6_SH03", ...] }
    ]
  }

Every shot in a short must be render-ready (animated: chosen video with an
interpolated clip on disk; static: chosen render PNG). Missing media aborts
that short with a clear message rather than shipping a broken draft.

The per-shot media/narration/duration resolution MIRRORS
ExportsService.buildManifest (narration timing: hold each shot for its VO +
0.5 s tail) so a short cut looks/sounds identical to the same shots in the full
export. BGM is intentionally omitted — a 30 s teaser gets its music in CapCut.

Run with a python that has psycopg2 (the seeders' python); it spawns
export_capcut.py with the pyJianYingDraft python (EXPORT_PYTHON).

  python scripts/export_shorts.py --plan scripts/painter_shorts_plan.json
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from datetime import datetime

import psycopg2
import psycopg2.extras

# ── paths / env ─────────────────────────────────────────────────────────────
SCRIPTS_DIR = os.path.dirname(os.path.abspath(__file__))
APP_ROOT    = os.path.dirname(SCRIPTS_DIR)                      # gen-studio/
EXPORT_SCRIPT = os.path.join(SCRIPTS_DIR, "export_capcut.py")
# The python that has pyJianYingDraft (same default as ExportsService).
EXPORT_PYTHON = (
    os.environ.get("EXPORT_PYTHON")
    or os.environ.get("PYTHON_BIN")
    or r"E:\kohya_ss\venv\Scripts\python.exe"
)

DB = dict(
    host=os.environ.get("PGHOST", "localhost"),
    dbname=os.environ.get("PGDATABASE", "gen_studio"),
    user=os.environ.get("PGUSER", "gen_studio"),
    password=os.environ.get("PGPASSWORD", "gen_studio"),
)

# Vertical Shorts default canvas.
DEF_WIDTH, DEF_HEIGHT, DEF_FPS = 1080, 1920, 30

# Full-length channel badge in the upper-right corner of every short — tells
# the viewer the full film is already on the channel. Rendered by
# export_capcut.py (_inject_text_overlay) with the style/placement the user
# set by hand once. Per-plan override: "overlay_text": "..." ("" disables).
DEF_OVERLAY_TEXT = "видео\nуже на\nканале"

# Narration-timing constants — identical to ExportsService.buildManifest.
TAIL_US     = 500_000      # breathing pause held after the VO line ends
MIN_SHOT_US = 2_500_000    # floor so a one-word line isn't a flash
NO_VO_US    = 4_000_000    # shot with no narration


def _log(msg: str) -> None:
    print(f"[shorts] {msg}", flush=True)


def _resolve_project(cur, id_or_slug: str):
    cur.execute(
        'SELECT id, slug FROM projects WHERE id = %s OR slug = %s LIMIT 1',
        (id_or_slug, id_or_slug),
    )
    row = cur.fetchone()
    if not row:
        sys.exit(f"project '{id_or_slug}' not found")
    return row["id"], row["slug"]


def _load_shots(cur, project_id: str):
    """shotCode -> dict with everything needed to resolve media + narration.
    Mirrors the joins ExportsService uses (chosen video render + approved TTS)."""
    cur.execute(
        '''
        SELECT sh.id AS shot_id, sh."shotCode", sh."renderMode", sh."chosenRender", sh."chosenVideoId",
               vr."interpFilename", vr."interpStatus", vr.params AS vparams,
               tj."outputFilename" AS tts_file, tj.text AS tts_text,
               tj."durationMs" AS tts_ms
        FROM shots sh
        LEFT JOIN video_renders vr ON vr.id = sh."chosenVideoId"
        LEFT JOIN tts_jobs      tj ON tj.id = sh."approvedTTSJobId"
        WHERE sh."projectId" = %s
        ''',
        (project_id,),
    )
    return {r["shotCode"]: dict(r) for r in cur.fetchall()}


def _load_bgm(cur, project_id: str):
    """Load the project's BGM so shorts can carry the act's music.
    Returns (shot_to_block, blocks_by_id) where blocks_by_id[bid] =
    {slug, sort, segments:[{seg_id, job_id, file, dur_sec, render_sec}]} with only
    approved+completed+on-disk segments, ordered by segment sortOrder."""
    cur.execute(
        'SELECT id, slug, "sortOrder" AS sort, "shotIds" AS shot_ids '
        'FROM narrative_blocks WHERE "projectId" = %s ORDER BY "sortOrder"',
        (project_id,),
    )
    blocks_by_id: dict = {}
    shot_to_block: dict = {}
    for b in cur.fetchall():
        blocks_by_id[b["id"]] = {"slug": b["slug"], "sort": b["sort"], "segments": []}
        for sid in (b["shot_ids"] or []):
            shot_to_block[sid] = b["id"]

    cur.execute(
        '''
        SELECT ms.id AS seg_id, ms."blockId" AS block_id, ms."sortOrder" AS sort,
               ms."durationSec" AS dur_sec, ms."approvedJobId" AS job_id,
               aj.status AS jstatus, aj."outputFilename" AS file, aj.params AS jparams
        FROM music_segments ms
        JOIN narrative_blocks nb ON nb.id = ms."blockId"
        LEFT JOIN audio_render_jobs aj ON aj.id = ms."approvedJobId"
        WHERE nb."projectId" = %s
        ORDER BY ms."blockId", ms."sortOrder"
        ''',
        (project_id,),
    )
    for r in cur.fetchall():
        blk = blocks_by_id.get(r["block_id"])
        if not blk:
            continue
        if not r["job_id"] or r["jstatus"] != "completed" or not r["file"]:
            continue  # unrendered/unapproved segment → no audio to place
        render_sec = (r["jparams"] or {}).get("renderSec") or r["dur_sec"]
        blk["segments"].append({
            "seg_id":     r["seg_id"],
            "job_id":     r["job_id"],
            "file":       r["file"],
            "dur_sec":    r["dur_sec"],
            "render_sec": render_sec,
        })
    return shot_to_block, blocks_by_id


def _build_short_music(shot_meta: list, blocks_by_id: dict, data_root: str,
                       total_us: int, lane: str) -> list:
    """Pick the act's BGM for a short (user rule): a short that sits in ONE act
    gets that act's first two music segments (sequential); a short that straddles
    an act SEAM gets the last segment of the first act + the first of the second,
    switching at the act boundary. All cues share one audio lane so export_capcut
    caps each by the next; the manifest's max_timeline_us trims the tail.

    shot_meta: [{block_id, start_us}] in play order (block_id may be None)."""
    def flac(seg):
        p = os.path.join(data_root, "bgm", blocks_by_id[seg["_bid"]]["slug"], seg["file"])
        return p if os.path.exists(p) else None

    def cue(seg, start_us):
        slug = blocks_by_id[seg["_bid"]]["slug"]
        path = os.path.join(data_root, "bgm", slug, seg["file"])
        if not os.path.exists(path):
            _log(f"WARN bgm flac missing, skipping: {path}")
            return None
        return {
            "blockSlug":          slug,
            "act":                lane,   # single lane → cap-by-next handles order
            "segmentId":          seg["seg_id"],
            "jobId":              seg["job_id"],
            "path":               path,
            "start_us":           int(start_us),
            "duration_us":        int(seg["dur_sec"] * 1_000_000),
            "render_duration_us": int(seg["render_sec"] * 1_000_000),
        }

    # Distinct blocks in order of appearance (shots are in play order).
    order = []
    for m in shot_meta:
        b = m["block_id"]
        if b and b in blocks_by_id and blocks_by_id[b]["segments"] and b not in order:
            order.append(b)
    if not order:
        return []

    def tag(b):  # remember which block a segment came from
        for s in blocks_by_id[b]["segments"]:
            s["_bid"] = b
        return blocks_by_id[b]["segments"]

    cues = []
    if len(order) == 1:
        # Single act → first two segments, sequential from 0.
        segs = tag(order[0])[:2]
        cursor = 0
        for s in segs:
            c = cue(s, cursor)
            if c:
                cues.append(c)
            cursor += int(s["render_sec"] * 1_000_000)   # next starts after this flac
    else:
        # Seam → last of first act + first of second act, switching at the boundary.
        first, second = order[0], order[1]
        boundary = next((m["start_us"] for m in shot_meta if m["block_id"] == second), 0)
        seg_a = tag(first)[-1]
        seg_b = tag(second)[0]
        c = cue(seg_a, 0)
        if c:
            cues.append(c)
        c = cue(seg_b, boundary)
        if c:
            cues.append(c)

    # Drop cues that would start at/after the short's end.
    return [c for c in cues if c["start_us"] < total_us]


def _resolve_shot_entry(shot: dict, data_root: str) -> dict:
    """Build one manifest shot entry (narration timing). Raises on missing media."""
    code = shot["shotCode"]
    shot_dir = os.path.join(data_root, "shots", code)

    # ── narration (per-shot wav) ──
    narration_us = None
    shot_narration = None
    tts_file = shot.get("tts_file")
    if tts_file:
        wav = os.path.join(shot_dir, tts_file)
        if os.path.exists(wav):
            ms = shot.get("tts_ms")
            if ms and ms > 0:
                true_wav_us = ms * 1000
            else:
                text = shot.get("tts_text") or ""
                true_wav_us = max(800_000, round(len(text) / 15 * 1_000_000))
            narration_us = true_wav_us
            shot_narration = {"path": wav, "duration_us": true_wav_us,
                              "text": shot.get("tts_text") or ""}
        else:
            _log(f"WARN {code}: approved TTS wav missing on disk ({wav}) — silent")

    # ── media + native length ──
    kind = None
    source_us = None
    if shot.get("renderMode") == "static":
        chosen = shot.get("chosenRender")
        if not chosen:
            raise RuntimeError(f"{code}: static shot has no chosenRender")
        media = os.path.join(shot_dir, chosen)
        if not os.path.exists(media):
            raise RuntimeError(f"{code}: chosen render PNG missing: {media}")
        kind = "image"
    else:
        interp = shot.get("interpFilename")
        if not shot.get("chosenVideoId") or not interp:
            raise RuntimeError(f"{code}: animated shot has no chosen+interpolated video")
        media = os.path.join(shot_dir, "videos_smooth", interp)
        if not os.path.exists(media):
            raise RuntimeError(f"{code}: interpolated mp4 missing: {media}")
        params = shot.get("vparams") or {}
        fps_p = params.get("fps") or 16
        len_p = params.get("length") or 81
        source_us = round(len_p / fps_p * 1_000_000)

    # ── timeline hold (narration timing) ──
    if narration_us is not None:
        duration_us = narration_us + TAIL_US
    else:
        duration_us = NO_VO_US if kind == "image" else (source_us or NO_VO_US)
    duration_us = max(duration_us, MIN_SHOT_US)
    # VO-fill floor for animated clips (no-op here since duration is already VO+tail).
    if kind is None and narration_us is not None:
        duration_us = max(duration_us, narration_us + TAIL_US)

    entry = {"shotCode": code, "path": media, "duration_us": int(duration_us),
             "narration": shot_narration}
    if kind:
        entry["kind"] = kind
    # source_us only when an animated clip is time-remapped (slow/trim).
    if kind is None and source_us is not None and source_us != duration_us:
        entry["source_us"] = int(source_us)
    return entry


def _capcut_drafts_root(output_root: str) -> str:
    # CAPCUT_DRAFTS_ROOT (see gen-studio/.env) wins, %LOCALAPPDATA% is the fallback
    # for a stock install / standalone runs without the env loaded. The override must
    # spell the path the way CapCut does: it matches projects by path string, so the
    # real location behind a junction registers as a SECOND copy of the same draft.
    root = os.environ.get("CAPCUT_DRAFTS_ROOT")
    if root:
        return root
    lad = os.environ.get("LOCALAPPDATA")
    if lad:
        return os.path.join(lad, "CapCut", "User Data", "Projects", "com.lveditor.draft")
    return output_root


def build_short_manifest(short: dict, shots_by_code: dict, slug: str,
                         width: int, height: int, fps: int, bg: str, fill: str, ts: str,
                         shot_to_block: dict, blocks_by_id: dict,
                         overlay_text: str = DEF_OVERLAY_TEXT) -> dict:
    short_slug = short["slug"]
    codes = short.get("shots") or []
    if not codes:
        sys.exit(f"short '{short_slug}' has no shots")

    data_root = os.path.join(APP_ROOT, "data", slug)
    entries = []
    shot_meta = []   # [{block_id, start_us}] in play order — for BGM placement
    running = 0
    for code in codes:
        shot = shots_by_code.get(code)
        if not shot:
            sys.exit(f"short '{short_slug}': shot '{code}' not found in project '{slug}'")
        try:
            entry = _resolve_shot_entry(shot, data_root)
        except RuntimeError as e:
            # One clean line instead of a traceback — the backend surfaces the
            # tail of stderr in its 400, so this is what the user actually sees.
            sys.exit(f"short '{short_slug}': {e}")
        shot_meta.append({"block_id": shot_to_block.get(shot.get("shot_id")), "start_us": running})
        running += entry["duration_us"]
        entries.append(entry)

    total_us = running
    music = _build_short_music(shot_meta, blocks_by_id, data_root, total_us, short_slug)

    draft_name  = f"{slug}_short_{short_slug}_{ts}"
    output_root = os.path.join(APP_ROOT, "data", slug, "exports", "shorts")
    os.makedirs(os.path.join(output_root, draft_name), exist_ok=True)

    return {
        "project_name":       f"{slug}_short_{short_slug}",
        "draft_name":         draft_name,
        "output_root":        output_root,
        "capcut_drafts_root": _capcut_drafts_root(output_root),
        "width":              width,
        "height":             height,
        "fps":                fps,
        "background_fill":    bg,
        "fill":               fill,
        "transition_preset":  "default",
        # Cap the timeline to the video length so BGM doesn't extend past the
        # last shot (cues otherwise play their full ~140s flac).
        "max_timeline_us": total_us,
        # «видео уже на канале» badge over the whole short ("" = none).
        "overlay_text": overlay_text,
        # The manifest "scenes" slot normally holds ACTS; for a short we fake a
        # single pseudo-act (sceneKey = short slug) so export_capcut.py can be
        # reused as-is. Its shots play in the plan's given order.
        "scenes": [{
            "sceneKey":  short_slug,
            "title":     short.get("title") or short_slug,
            "narration": None,
            "shots":     entries,
        }],
        # The act's music (first-two / seam last+first per the user rule).
        "music_tracks": music,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", required=True, help="path to the shorts plan json")
    ap.add_argument("--only", help="build ONLY the short with this slug (per-short "
                                   "export from the UI); default builds all shorts")
    ap.add_argument("--out", help="write the result json ({project,shorts:[...]}) to this "
                                  "path (the backend reads it instead of parsing stdout)")
    ap.add_argument("--dry-run", action="store_true",
                    help="write manifests but do not spawn the CapCut exporter")
    args = ap.parse_args()

    with open(args.plan, "r", encoding="utf-8") as f:
        plan = json.load(f)

    id_or_slug = plan["project"]
    # "cover" (default) enlarges each clip to FILL the 9:16 frame (crops the sides,
    # content is big). Set fill:"fit" + background_fill:"blur" for the letterbox look.
    fill   = str(plan.get("fill", "cover")).strip().lower()
    bg     = str(plan.get("background_fill", "")).strip().lower()
    width  = int(plan.get("width", DEF_WIDTH))
    height = int(plan.get("height", DEF_HEIGHT))
    fps    = int(plan.get("fps", DEF_FPS))
    overlay = str(plan.get("overlay_text", DEF_OVERLAY_TEXT))
    shorts = plan.get("shorts") or []
    if not shorts:
        sys.exit("plan has no shorts")
    if args.only:
        shorts = [s for s in shorts if s.get("slug") == args.only]
        if not shorts:
            sys.exit(f"--only '{args.only}': no short with that slug in the plan")

    if not os.path.exists(EXPORT_SCRIPT):
        sys.exit(f"export_capcut.py missing: {EXPORT_SCRIPT}")
    if not args.dry_run and not os.path.exists(EXPORT_PYTHON):
        sys.exit(f"EXPORT_PYTHON missing: {EXPORT_PYTHON} (set EXPORT_PYTHON env)")

    conn = psycopg2.connect(**DB)
    conn.set_client_encoding("UTF8")
    cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
    project_id, slug = _resolve_project(cur, id_or_slug)
    shots_by_code = _load_shots(cur, project_id)
    shot_to_block, blocks_by_id = _load_bgm(cur, project_id)
    cur.close()
    conn.close()

    ts = datetime.now().strftime("%Y%m%d_%H%M")
    results = []
    for short in shorts:
        manifest = build_short_manifest(short, shots_by_code, slug,
                                        width, height, fps, bg, fill, ts,
                                        shot_to_block, blocks_by_id,
                                        overlay_text=overlay)
        n_shots = len(manifest["scenes"][0]["shots"])
        total_us = sum(s["duration_us"] for s in manifest["scenes"][0]["shots"])
        n_bgm = len(manifest["music_tracks"])
        mpath = os.path.join(manifest["output_root"], manifest["draft_name"], "manifest.json")
        with open(mpath, "w", encoding="utf-8") as f:
            json.dump(manifest, f, ensure_ascii=False, indent=2)
        _log(f"{manifest['draft_name']}: {n_shots} shots, ~{total_us/1e6:.1f}s, {n_bgm} bgm cue(s) "
             f"({width}x{height}, fill={fill or bg or 'fit'})")

        row_base = {"slug": short["slug"], "title": short.get("title") or short["slug"]}
        if args.dry_run:
            results.append({**row_base, "draft_name": manifest["draft_name"], "manifest": mpath,
                            "shots": n_shots, "seconds": round(total_us / 1e6, 1)})
            continue

        proc = subprocess.run(
            [EXPORT_PYTHON, "-X", "utf8", EXPORT_SCRIPT, "--manifest", mpath],
            env={**os.environ, "PYTHONIOENCODING": "utf-8"},
            capture_output=True, text=True,
        )
        if proc.returncode != 0:
            _log(f"EXPORTER FAILED for {manifest['draft_name']} (exit {proc.returncode})")
            _log((proc.stderr or "").strip()[-1500:])
            sys.exit(1)
        draft_path = os.path.join(manifest["capcut_drafts_root"], manifest["draft_name"])
        _log(f"  -> draft ready: {draft_path}")
        results.append({**row_base, "draft_name": manifest["draft_name"], "draft_path": draft_path,
                        "shots": n_shots, "seconds": round(total_us / 1e6, 1)})

    out_obj = {"project": slug, "shorts": results}
    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            json.dump(out_obj, f, ensure_ascii=False, indent=2)
    print(json.dumps(out_obj, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

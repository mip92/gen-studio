def main():
    conn = psycopg2.connect(**DSN); conn.autocommit = False; cur = conn.cursor()
    updated = missing = 0
    try:
        for code, txt in VO.items():
            cur.execute('UPDATE shots SET "narrationText"=%s, '
                '"promptFields"=jsonb_set("promptFields",\'{narrationRu}\',to_jsonb(%s::text)), '
                '"updatedAt"=now() WHERE "projectId"=%s AND "shotCode"=%s',
                (txt, txt, PROJ_ID, code))
            if cur.rowcount == 0: missing += 1; print("  MISSING:", code)
            else: updated += cur.rowcount
        conn.commit()
        # report new VO length distribution
        cur.execute('''SELECT "narrationText" FROM shots WHERE "projectId"=%s
                       AND coalesce(trim("narrationText"),'')<>'' ''',(PROJ_ID,))
        secs=[len(r[0].split())/2.4 for r in cur.fetchall()]
        short=sum(1 for s in secs if s<4.0); inrange=sum(1 for s in secs if 4.0<=s<=8.5)
        print(f"OK VO v2: updated {updated}, missing {missing}")
        print(f"   voiced {len(secs)} | <4s:{short}  5-8s-ish:{inrange}  >8.5s:{sum(1 for s in secs if s>8.5)}")
        print(f"   avg {sum(secs)/len(secs):.1f}s  min {min(secs):.1f}s  max {max(secs):.1f}s")
    except Exception as e:
        conn.rollback(); print("ROLLBACK:", repr(e).encode('ascii','replace').decode()); sys.exit(1)
    finally:
        cur.close(); conn.close()

if __name__ == "__main__":
    main()

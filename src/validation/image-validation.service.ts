import { Injectable, Logger } from '@nestjs/common';
import { spawn } from 'child_process';
import { existsSync, mkdirSync, readFileSync, rmSync } from 'fs';
import * as os from 'os';
import * as path from 'path';
import { PrismaService } from '../prisma/prisma.service';

const APP_ROOT   = process.env.APP_ROOT ?? path.resolve(__dirname, '..', '..', '..');
const KOHYA_PYTHON     = process.env.KOHYA_PYTHON ?? 'E:\\kohya_ss\\venv\\Scripts\\python.exe';
const VISION_RESIZE_SCRIPT = path.join(APP_ROOT, 'scripts', 'vision_resize.py');

const OLLAMA_URL   = process.env.OLLAMA_URL ?? 'http://127.0.0.1:11434';
/** Vision model tag. qwen3-vl:8b fits entirely in 16 GB VRAM (≈6 GB) so it runs
 *  ~10× faster than the 30B MoE which partially offloads to CPU. Overridable. */
const VALIDATION_MODEL = process.env.OLLAMA_VALIDATION_MODEL ?? 'qwen3-vl:8b';
/** Longest-side px we downscale candidates to before scoring — see vision_resize.py. */
const VISION_MAX_DIM   = Number(process.env.VISION_MAX_DIM ?? 768);
/** Keep the model resident between per-candidate calls so we pay the load once. */
const KEEP_ALIVE = process.env.OLLAMA_KEEP_ALIVE ?? '5m';
/** Per-image request ceiling. A warm 8B answers in a few seconds; the 30B on
 *  CPU-offload can take ~35s. Generous so a slow card doesn't false-fail. */
const REQUEST_TIMEOUT_MS = Number(process.env.VALIDATION_TIMEOUT_MS ?? 180_000);

/** One candidate's verdict as returned by the vision model. */
export interface CandidateVerdict {
  filename:      string;
  score:         number;          // 0-100 overall (prompt match + technical quality)
  matchesPrompt: boolean;         // does the frame show what it should?
  severe:        boolean;         // unusable: anatomy horror / wrong or missing subject / intruder
  issues:        string[];        // concrete defects (bad hands, garbled text, wrong subject…)
  error?:        string;          // set if this candidate could not be scored
}


@Injectable()
export class ImageValidationService {
  private readonly logger = new Logger(ImageValidationService.name);

  constructor(private readonly prisma: PrismaService) {}

  /** Typed prisma is regenerated by `prisma migrate`; cast keeps the build green
   *  in the window before the client knows about image_validation_jobs. */
  private get db(): any { return this.prisma as any; }

  // ── Queue-aware API (used by PipelineQueueService) ──────────────────────────

  async findNextPending() {
    return this.db.imageValidationJob.findFirst({
      where:   { status: 'pending' },
      orderBy: { queuedAt: 'asc' },
    });
  }

  /**
   * Enqueue a validation pass for a shot: snapshots the current candidate pool
   * and the expected prompt/narration so the queue worker can score it later.
   * No-op (returns null) if there are fewer than 2 candidates — nothing to pick
   * between — or if a validation for this shot is already pending/running.
   */
  async enqueue(shotId: string, expectedPrompt: string | null) {
    const shot = await this.prisma.shot.findUnique({ where: { id: shotId } });
    if (!shot) return null;
    const candidates = ((shot.renderedImages as Array<{ filename: string }> | null) ?? [])
      .map((r) => r.filename)
      .filter(Boolean);
    if (candidates.length < 2) return null;

    const inflight = await this.db.imageValidationJob.count({
      where: { shotId, status: { in: ['pending', 'running'] } },
    });
    if (inflight > 0) return null;

    // Fall back to the shot's hand-written positive when the caller didn't pass
    // the resolved render prompt (e.g. the manual "re-validate" button).
    const pf = (shot.promptFields ?? {}) as Record<string, unknown>;
    const expected = expectedPrompt
      ?? (typeof pf.positive === 'string' && pf.positive.trim() ? pf.positive : null);

    return this.db.imageValidationJob.create({
      data: {
        shotId,
        status:         'pending',
        expectedPrompt: expected ?? undefined,
        narration:      shot.narrationText ?? undefined,
        candidates:     candidates as any,
      },
    });
  }

  /**
   * Score every candidate of a validation job and set the winner as the shot's
   * chosenRender. Assumes the caller (PipelineQueueService.dispatchValidation)
   * has already marked the job `running` and stopped ComfyUI so the GPU is free.
   * Sets the job `completed`/`failed` on the way out.
   */
  async run(jobId: string): Promise<void> {
    const job = await this.db.imageValidationJob.findUnique({ where: { id: jobId } });
    if (!job) return;
    try {
      const shot = await this.prisma.shot.findUnique({
        where:   { id: job.shotId },
        include: {
          project: { select: { slug: true } },
          // Participants → each character's canonical look (promptBase). Fed to
          // the validator so it does NOT flag intended features (tattoos, marks,
          // hair, outfit) as defects, and CAN check the right person is shown.
          participants: { include: {
            character: { select: { displayName: true } },
            profile:   { select: { promptBase: true } },
          } },
        },
      });
      if (!shot?.project) throw new Error(`shot ${job.shotId} or its project not found`);

      const characterNotes = (shot.participants ?? [])
        .map((p: any) => {
          const name = p.character?.displayName?.trim();
          const base = p.profile?.promptBase?.trim();
          if (!base) return null;
          return name ? `${name}: ${base}` : base;
        })
        .filter(Boolean)
        .join(' | ') || null;

      // Re-read the live candidate pool (a render may have appended more since
      // enqueue) and intersect with what still exists on disk.
      const shotDir = path.join(APP_ROOT, 'data', shot.project.slug, 'shots', shot.shotCode);
      const pool = ((shot.renderedImages as Array<{ filename: string }> | null) ?? [])
        .map((r) => r.filename)
        .filter((f) => f && existsSync(path.join(shotDir, f)));
      if (pool.length === 0) throw new Error('no candidate files on disk to validate');

      const verdicts = await this.scoreCandidates(shotDir, pool, job.expectedPrompt, job.narration, characterNotes);

      // A candidate is ACCEPTABLE only if it scored without error, has no severe
      // defect, and actually matches the prompt. We never "settle" for the
      // least-bad frame — if nothing is acceptable, we pick NOTHING and instead
      // propose a better prompt for the user to approve.
      const acceptable = verdicts
        .filter((v) => !v.error && !v.severe && v.matchesPrompt)
        .sort((a, b) => b.score - a.score);
      const winner = acceptable[0] ?? null;

      let suggestedPrompt: string | null = null;
      if (!winner) {
        suggestedPrompt = await this.suggestPrompt(job.expectedPrompt, job.narration, verdicts).catch((e) => {
          this.logger.warn(`suggestPrompt failed: ${e?.message ?? e}`);
          return null;
        });
      }

      await this.db.imageValidationJob.update({
        where: { id: jobId },
        data:  {
          status:          'completed',
          result:          verdicts as any,
          chosenFilename:  winner?.filename ?? null,
          suggestedPrompt: suggestedPrompt ?? null,
          completedAt:     new Date(),
        },
      });
      // Set chosenRender to the winner, or CLEAR it when no candidate passed —
      // a shot with an all-failed batch must not look "done".
      await this.prisma.shot.update({
        where: { id: job.shotId },
        data:  { chosenRender: winner?.filename ?? null },
      });
      if (winner) {
        this.logger.log(`Validation ${jobId}: picked ${winner.filename} (score ${winner.score}) for shot ${shot.shotCode} out of ${pool.length}`);
      } else {
        this.logger.warn(`Validation ${jobId}: NO acceptable candidate for shot ${shot.shotCode} (${pool.length} scored) — cleared chosenRender, ${suggestedPrompt ? 'suggested a new prompt' : 'no suggestion generated'}`);
      }
    } catch (e: any) {
      this.logger.error(`Validation ${jobId} failed: ${e?.message ?? e}`);
      await this.db.imageValidationJob.update({
        where: { id: jobId },
        data:  { status: 'failed', errorMessage: String(e?.message ?? e), completedAt: new Date() },
      }).catch(() => {});
    }
  }

  // ── Scoring internals ───────────────────────────────────────────────────────

  private async scoreCandidates(
    shotDir: string,
    filenames: string[],
    expectedPrompt: string | null,
    narration: string | null,
    characterNotes: string | null,
  ): Promise<CandidateVerdict[]> {
    // Downscale all candidates in one Python pass → a temp dir on E: (never C:).
    const tmpDir = path.join(os.tmpdir(), 'gen-studio-vision', `${Date.now()}-${Math.floor(Math.random() * 1e6)}`);
    mkdirSync(tmpDir, { recursive: true });
    const pairs: Array<{ filename: string; small: string }> = filenames.map((f) => ({
      filename: f,
      small:    path.join(tmpDir, f),
    }));
    try {
      await this.resize(pairs.map((p) => [path.join(shotDir, p.filename), p.small] as [string, string]));
      const sys = this.buildScoringInstruction(expectedPrompt, narration, characterNotes);
      const verdicts: CandidateVerdict[] = [];
      for (const p of pairs) {
        const imgPath = existsSync(p.small) ? p.small : path.join(shotDir, p.filename); // fall back to full-res
        verdicts.push(await this.scoreOne(p.filename, imgPath, sys));
      }
      return verdicts;
    } finally {
      try { rmSync(tmpDir, { recursive: true, force: true }); } catch { /* best effort */ }
    }
  }

  /** Build the instruction describing what the frame is supposed to show. */
  private buildScoringInstruction(expectedPrompt: string | null, narration: string | null, characterNotes: string | null): string {
    const parts: string[] = [
      'You are a ruthless art director doing QC on ONE AI-generated video frame. Examine the ENTIRE frame, not just the main subject: every person and body, the background, windows, mirrors, reflections, edges and corners.',
    ];
    if (expectedPrompt && expectedPrompt.trim()) {
      parts.push(`REQUIRED CONTENT — the frame must depict exactly this: "${expectedPrompt.trim()}". This text MIXES art-style/rendering/camera directions (e.g. "cell-shaded", "neon glow", "comic book panel", "no photorealism", "no 3D render", "ink outline", "wide shot / WS", "eye-level", "push-in", "16:9") with the actual scene. IGNORE the style, rendering and camera tokens entirely — do NOT reward or penalize them. Judge ONLY the scene: WHICH subjects are present, WHAT they are doing, and the SETTING. Every subject named in the scene (e.g. the main character AND a child, or "streamers", if named) must be present, whole and correct. If a named subject is missing (e.g. the prompt asks for people but the frame is an empty room), or an extra person/figure appears that was NOT asked for (a stranger in a window / background), that is a mismatch.`);
    }
    if (narration && narration.trim()) {
      parts.push(`It accompanies this narration, so it must show exactly the subject the narration names: "${narration.trim()}".`);
    }
    if (characterNotes && characterNotes.trim()) {
      parts.push(`KNOWN CHARACTER DESIGN — the character(s) in this shot canonically look like this: "${characterNotes.trim()}". These features (tattoos, marks, logos, hairstyle, clothing, accessories) are INTENTIONAL parts of the character. Do NOT report them as defects, artifacts, or "extra elements". Instead, USE this to check the depicted person is the RIGHT character; a person who clearly contradicts this design is a mismatch.`);
    }
    parts.push(
      'Check anatomy on EVERY person: a complete, natural body correctly attached to the head. Flag detached / floating / severed heads, a head with no body or torso, missing or extra limbs, fused or duplicated bodies, malformed hands or fingers, melted or distorted faces. ALSO scrutinise PROPORTIONS AND JOINTS: flag limbs that are too long / stretched / elongated, arms or legs bent at impossible or unnatural angles, dislocated or backwards joints, and grossly wrong body proportions — these are common and easy to miss, so look carefully at every arm and leg. Also flag: an unexpected extra person or face anywhere (background, window, doorway, mirror), garbled or nonsensical text, mangled reflections, and gross artifacts.',
      'Return JSON: "matches_prompt" (true ONLY if all required subjects are present and correct AND there is no unwanted extra person); ' +
      '"severe_defect" (true if the frame is UNUSABLE — e.g. a detached/bodiless head, a missing or wrong main subject, a fused body, a badly deformed / elongated / wrongly-angled limb, or an intruding stranger); ' +
      '"score" (integer 0-100: start at 100 and subtract hard for every defect; a clean frame with only trivial nitpicks stays high, but any real anatomy problem drops it well below 70; any severe_defect forces score <= 15); ' +
      '"issues" (array of short concrete strings for exactly what you see; empty only if the frame is truly clean).',
    );
    return parts.join(' ');
  }

  private async scoreOne(filename: string, imgPath: string, instruction: string): Promise<CandidateVerdict> {
    const b64 = readFileSync(imgPath).toString('base64');
    let lastErr = '';
    // Up to 2 attempts: qwen3-vl occasionally returns an EMPTY message.content
    // (nothing to parse → "Unexpected end of JSON input"). A retry almost always
    // yields a proper object. We use format:'json' (proven reliable in testing)
    // rather than a JSON-schema object, which was the source of the empty replies.
    for (let attempt = 1; attempt <= 2; attempt++) {
      try {
        const res = await fetch(`${OLLAMA_URL}/api/chat`, {
          method:  'POST',
          headers: { 'Content-Type': 'application/json' },
          body:    JSON.stringify({
            model:      VALIDATION_MODEL,
            stream:     false,
            format:     'json',
            // Thinking ON: reasoning makes the model actually scrutinise anatomy
            // (elongated limbs, bad angles) instead of rubber-stamping ~98. This
            // is the config that reliably caught defects in testing. The retry +
            // empty-content guard below cover the rare empty reply.
            keep_alive: KEEP_ALIVE,
            messages:   [{ role: 'user', content: instruction, images: [b64] }],
          }),
          signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
        });
        if (!res.ok) throw new Error(`Ollama ${res.status}: ${await res.text()}`);
        const data = (await res.json()) as { message?: { content?: string } };
        const content = (data.message?.content ?? '').trim();
        if (!content) throw new Error('empty content from model');
        const parsed = JSON.parse(content);
        const severe = parsed.severe_defect === true;
        let score = clampScore(parsed.score);
        if (severe && score > 15) score = 15;   // enforce the rubric even if the model forgets
        return {
          filename,
          score,
          matchesPrompt: parsed.matches_prompt === true && !severe,
          severe,
          issues:        Array.isArray(parsed.issues) ? parsed.issues.map(String) : [],
        };
      } catch (e: any) {
        lastErr = String(e?.message ?? e);
        this.logger.warn(`scoreOne ${filename} attempt ${attempt} failed: ${lastErr}`);
      }
    }
    return { filename, score: -1, matchesPrompt: false, severe: false, issues: [], error: lastErr };
  }

  /**
   * When no candidate passed, ask the model to rewrite the positive prompt so a
   * re-render fixes the recurring failures. Text-only (no image) → fast. Returns
   * the improved prompt text, or null if the model gave nothing useful.
   */
  private async suggestPrompt(
    expectedPrompt: string | null,
    narration: string | null,
    verdicts: CandidateVerdict[],
  ): Promise<string | null> {
    const issues = Array.from(new Set(verdicts.flatMap((v) => v.issues))).slice(0, 12);
    if (!expectedPrompt?.trim() && issues.length === 0) return null;
    const ask = [
      'An image generator produced several candidates for one shot and ALL of them failed quality control.',
      expectedPrompt?.trim() ? `The intended positive prompt was: "${expectedPrompt.trim()}".` : '',
      narration?.trim() ? `The frame accompanies this narration: "${narration.trim()}".` : '',
      issues.length ? `The recurring problems across the candidates were: ${issues.join('; ')}.` : '',
      'Rewrite the POSITIVE prompt so a re-render fixes these specific problems while keeping the original intent, subject, and visual style. Be concrete and visual; explicitly state what each subject is doing and any element the generator kept getting wrong. Return ONLY the rewritten positive prompt as plain text — no preamble, no quotes, no explanation.',
    ].filter(Boolean).join(' ');

    const res = await fetch(`${OLLAMA_URL}/api/generate`, {
      method:  'POST',
      headers: { 'Content-Type': 'application/json' },
      // think:false — qwen3-vl is a reasoning model; with thinking on it can burn
      // the whole output on the `thinking` field and return an EMPTY `response`.
      // We only want the rewritten prompt, so answer directly.
      body:    JSON.stringify({ model: VALIDATION_MODEL, prompt: ask, stream: false, think: false, keep_alive: KEEP_ALIVE }),
      signal:  AbortSignal.timeout(REQUEST_TIMEOUT_MS),
    });
    if (!res.ok) throw new Error(`Ollama ${res.status}: ${await res.text()}`);
    const data = (await res.json()) as { response?: string };
    const text = (data.response ?? '').trim().replace(/^["'`]+|["'`]+$/g, '').trim();
    return text.length > 0 ? text : null;
  }

  /** Spawn vision_resize.py once for all [src,dest] pairs. Best-effort: on any
   *  failure the caller falls back to the full-res image for that candidate. */
  private resize(pairs: Array<[string, string]>): Promise<void> {
    return new Promise((resolve) => {
      if (pairs.length === 0) return resolve();
      if (!existsSync(KOHYA_PYTHON) || !existsSync(VISION_RESIZE_SCRIPT)) {
        this.logger.warn('resize: python or vision_resize.py missing — scoring full-res');
        return resolve();
      }
      const argv = [VISION_RESIZE_SCRIPT, String(VISION_MAX_DIM)];
      for (const [s, d] of pairs) { argv.push(s, d); }
      const proc = spawn(KOHYA_PYTHON, argv, { stdio: ['ignore', 'ignore', 'pipe'] });
      let err = '';
      proc.stderr.on('data', (c: Buffer) => { err += c.toString(); });
      proc.on('close', (code) => {
        if (code !== 0 && err.trim()) this.logger.warn(`vision_resize rc=${code}: ${err.trim().slice(0, 300)}`);
        resolve();
      });
      proc.on('error', (e) => { this.logger.warn(`vision_resize spawn error: ${e.message}`); resolve(); });
    });
  }
}

function clampScore(n: unknown): number {
  const v = Number(n);
  if (!Number.isFinite(v)) return 0;
  return Math.max(0, Math.min(100, Math.round(v)));
}
